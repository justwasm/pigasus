// BinaryInfo holds inspected metadata for the reference binary.
type BinaryInfo struct {
	Path      string `json:"path"`
	Version   string `json:"version"`
	SHA256    string `json:"sha256"`
	SizeBytes int64  `json:"size_bytes"`
	Available bool   `json:"available"`
	Error     string `json:"error,omitempty"`
}

// MethodsCheck contains the outcome of comparing RPC methods.
type MethodsCheck struct {
	ExpectedCount int      `json:"expected_count"`
	LiveCount     int      `json:"live_count"`
	Drifted       bool     `json:"drifted"`
	ServiceName   string   `json:"service_name,omitempty"`
	Diff          []string `json:"diff,omitempty"`
	Note          string   `json:"note,omitempty"`
}

// EmbedAssetsCheck contains the outcome of inspecting embedded assets.
type EmbedAssetsCheck struct {
	ExpectedRecords int      `json:"expected_records"`
	LiveRecords     int      `json:"live_records"`
	TotalBytes      int64    `json:"total_bytes"`
	ZipArchives     int      `json:"zip_archives"`
	Drifted         bool     `json:"drifted"`
	Diff            []string `json:"diff,omitempty"`
}

// ToolsCheck contains the outcome of inspecting tool definitions.
type ToolsCheck struct {
	ExpectedCount int      `json:"expected_count"`
	LiveCount     int      `json:"live_count"`
	Drifted       bool     `json:"drifted"`
	Missing       []string `json:"missing,omitempty"`
	Added         []string `json:"added,omitempty"`
	Diff          []string `json:"diff,omitempty"`
}

// CanaryReport is the machine-readable evaluation report generated by RunCanary.
type CanaryReport struct {
	Timestamp              string           `json:"timestamp"`
	Version                string           `json:"version"`
	SHA256                 string           `json:"sha256"`
	BinaryPath             string           `json:"binary_path"`
	PinnedVersion          string           `json:"pinned_version"`
	LagAcknowledgedThrough string           `json:"lag_acknowledged_through,omitempty"`
	HasDrift               bool             `json:"has_drift"`
	DriftItems             []string         `json:"drift_items"`
	Binary                 BinaryInfo       `json:"binary"`
	Methods                MethodsCheck     `json:"methods"`
	EmbedAssets            EmbedAssetsCheck `json:"embed_assets"`
	Tools                  ToolsCheck       `json:"tools"`
	Status                 Status           `json:"status"`
	Summary                string           `json:"summary"`
}

// InspectBinary computes the SHA-256 hash, file size, and version of binPath.
func InspectBinary(binPath string) (*BinaryInfo, error) {
	info := &BinaryInfo{Path: binPath}
	fi, err := os.Stat(binPath)
	if err != nil {
		info.Error = err.Error()
		return info, err
	}
	info.Available = true
	info.SizeBytes = fi.Size()

	f, err := os.Open(binPath)
	if err != nil {
		info.Error = err.Error()
		return info, err
	}
	defer f.Close()

	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		info.Error = err.Error()
		return info, err
	}
	info.SHA256 = hex.EncodeToString(h.Sum(nil))

	ver, err := BinaryVersion(binPath)
	if err != nil {
		info.Version = "unknown"
		info.Error = err.Error()
	} else {
		info.Version = ver
	}
	return info, nil
}

// InspectMethods compares the live binary's RPC methods against the fixture baseline.
func InspectMethods(binPath string, repoRoot string) (*MethodsCheck, error) {
	check := &MethodsCheck{
		ServiceName: "JetskiRemoteAgentProxyService",
	}

	// 1. Read baseline fixture
	fixturePath := filepath.Join(repoRoot, "internal/remotecontrol/testdata/jetski_remote_agent_proxy_1.4.7.txt")
	expectedMethods := loadMethodsFixture(fixturePath)
	check.ExpectedCount = len(expectedMethods)
	if check.ExpectedCount == 0 {
		check.ExpectedCount = 79 // reference fallback
	}

	if binPath == "" {
		check.Note = "No binary provided for live method inspection"
		return check, nil
	}

	// 2. Try extracting FileDescriptorProto from binary
	fd, err := ExtractProtoDescriptor(binPath, "google/gca/aicode/v1main/remote_agent_proxy.proto")
	if err == nil && len(fd.GetService()) > 0 {
		svc := fd.GetService()[0]
		check.ServiceName = svc.GetName()
		methods := svc.GetMethod()
		check.LiveCount = len(methods)

		liveMap := make(map[string]bool, len(methods))
		for _, m := range methods {
			liveMap[m.GetName()] = true
		}
		var missing []string
		for _, exp := range expectedMethods {
			if !liveMap[exp] {
				missing = append(missing, exp)
			}
		}
		if len(missing) > 0 {
			check.Diff = append(check.Diff, fmt.Sprintf("%d expected methods missing from live descriptor: %v", len(missing), missing))
		}
		if check.LiveCount != check.ExpectedCount {
			check.Drifted = true
			check.Diff = append(check.Diff, fmt.Sprintf("method count drifted: expected %d, got %d (delta %+d)",
				check.ExpectedCount, check.LiveCount, check.LiveCount-check.ExpectedCount))
		}
		return check, nil
	}

	// 3. Fallback: string scan in binary for known methods
	data, readErr := os.ReadFile(binPath)
	if readErr != nil {
		check.Note = fmt.Sprintf("Failed to read binary for method inspection: %v", readErr)
		return check, nil
	}

	foundCount := 0
	for _, m := range expectedMethods {
		if bytes.Contains(data, []byte(m)) {
			foundCount++
		}
	}
	check.LiveCount = foundCount
	if foundCount != check.ExpectedCount {
		check.Drifted = true
		check.Diff = append(check.Diff, fmt.Sprintf("known method presence: %d/%d found", foundCount, check.ExpectedCount))
	}
	return check, nil
}

func loadMethodsFixture(path string) []string {
	f, err := os.Open(path)
	if err != nil {
		return nil
	}
	defer f.Close()

	var methods []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := strings.Split(line, "\t")
		if len(parts) >= 1 && parts[0] != "" {
			methods = append(methods, parts[0])
		}
	}
	return methods
}

// InspectEmbedAssets scans binary embedded assets and compares with the baseline.
func InspectEmbedAssets(binPath string, repoRoot string) (*EmbedAssetsCheck, error) {
	check := &EmbedAssetsCheck{
		ExpectedRecords: 353, // baseline reference lexers & styles
	}

	// Read reference lexers baseline if available
	lexPath := filepath.Join(repoRoot, "internal/ui/mdrender/testdata/reference_lexers.txt")
	if raw, err := os.ReadFile(lexPath); err == nil {
		lines := 0
		sc := bufio.NewScanner(bytes.NewReader(raw))
		for sc.Scan() {
			t := strings.TrimSpace(sc.Text())
			if t != "" && !strings.HasPrefix(t, "#") {
				lines++
			}
		}
		if lines > 0 {
			check.ExpectedRecords = lines
		}
	}

	if binPath == "" {
		return check, nil
	}

	count, totalBytes, zipCount, err := ScanEmbeddedAssets(binPath)
	if err != nil {
		check.Diff = append(check.Diff, fmt.Sprintf("scan error: %v", err))
		return check, nil
	}

	check.LiveRecords = count
	check.TotalBytes = totalBytes
	check.ZipArchives = zipCount

	if check.LiveRecords != check.ExpectedRecords {
		check.Drifted = true
		check.Diff = append(check.Diff, fmt.Sprintf("embedded records drifted: baseline %d, live %d (delta %+d)",
			check.ExpectedRecords, check.LiveRecords, check.LiveRecords-check.ExpectedRecords))
	}
	return check, nil
}

// InspectTools compares tool definitions between the reference baseline and live binary.
func InspectTools(binPath string, repoRoot string) (*ToolsCheck, error) {
	check := &ToolsCheck{}

	// 1. Read tool names baseline
	toolPath := filepath.Join(repoRoot, "internal/app/tools/surface/testdata/tool_names_1.4.7.txt")
	expectedTools := loadToolNames(toolPath)
	check.ExpectedCount = len(expectedTools)
	if check.ExpectedCount == 0 {
		check.ExpectedCount = 63 // reference fallback
	}

	if binPath == "" {
		return check, nil
	}

	data, err := os.ReadFile(binPath)
	if err != nil {
		check.Diff = append(check.Diff, fmt.Sprintf("binary read error: %v", err))
		return check, nil
	}

	liveFound := 0
	for _, name := range expectedTools {
		if bytes.Contains(data, []byte(name)) {
			liveFound++
		} else {
			check.Missing = append(check.Missing, name)
		}
	}
	check.LiveCount = liveFound

	if len(check.Missing) > 0 {
		check.Drifted = true
		check.Diff = append(check.Diff, fmt.Sprintf("missing %d expected tools: %v", len(check.Missing), check.Missing))
	} else if check.LiveCount != check.ExpectedCount {
		check.Drifted = true
		check.Diff = append(check.Diff, fmt.Sprintf("tools count: expected %d, matched %d", check.ExpectedCount, check.LiveCount))
	}
	return check, nil
}

func loadToolNames(path string) []string {
	f, err := os.Open(path)
	if err != nil {
		return nil
	}
	defer f.Close()

	var tools []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		t := strings.TrimSpace(sc.Text())
		if t != "" && !strings.HasPrefix(t, "#") {
			tools = append(tools, t)
		}
	}
	sort.Strings(tools)
	return tools
}

// RunCanary performs the full canary inspection and returns a CanaryReport.
func RunCanary(repoRoot string, binPath string) (*CanaryReport, error) {
	if binPath == "" {
		binPath = FindBinary()
	}

	lock, err := LoadFrom(filepath.Join(repoRoot, filepath.FromSlash(LockPath)))
	if err != nil {
		return nil, fmt.Errorf("load lock: %w", err)
	}

	status := Resolve(repoRoot, lock)
	rep := &CanaryReport{
		Timestamp:              time.Now().UTC().Format(time.RFC3339),
		BinaryPath:             binPath,
		PinnedVersion:          lock.Version,
		LagAcknowledgedThrough: lock.LagAcknowledgedThrough,
		Status:                 status,
	}

	// 1. Binary Info & Hash
	if binPath != "" {
		bInfo, bErr := InspectBinary(binPath)
		if bErr == nil {
			rep.Binary = *bInfo
			rep.Version = bInfo.Version
			rep.SHA256 = bInfo.SHA256
		} else {
			rep.Binary = BinaryInfo{Path: binPath, Available: false, Error: bErr.Error()}
		}
	} else {
		rep.Binary = BinaryInfo{Available: false, Error: "no reference binary located"}
	}

	// Check Hash match if lock recorded one or identity exists
	if lock.BinarySHA256 != "" && rep.SHA256 != "" {
		if rep.SHA256 != lock.BinarySHA256 {
			rep.DriftItems = append(rep.DriftItems, fmt.Sprintf("binary SHA-256 changed: want %s, got %s",
				lock.BinarySHA256, rep.SHA256))
		}
	}

	// 2. Methods Check
	mCheck, mErr := InspectMethods(binPath, repoRoot)
	if mErr == nil && mCheck != nil {
		rep.Methods = *mCheck
		if mCheck.Drifted {
			rep.DriftItems = append(rep.DriftItems, fmt.Sprintf("methods drifted: %s", strings.Join(mCheck.Diff, "; ")))
		}
	}

	// 3. Embedded Assets Check
	eCheck, eErr := InspectEmbedAssets(binPath, repoRoot)
	if eErr == nil && eCheck != nil {
		rep.EmbedAssets = *eCheck
		if eCheck.Drifted {
			rep.DriftItems = append(rep.DriftItems, fmt.Sprintf("embedded assets drifted: %s", strings.Join(eCheck.Diff, "; ")))
		}
	}

	// 4. Tools Check
	tCheck, tErr := InspectTools(binPath, repoRoot)
	if tErr == nil && tCheck != nil {
		rep.Tools = *tCheck
		if tCheck.Drifted {
			rep.DriftItems = append(rep.DriftItems, fmt.Sprintf("tools drifted: %s", strings.Join(tCheck.Diff, "; ")))
		}
	}

	// 5. Lock & Artifact Status
	if status.RepoBroken() {
		for _, m := range status.Missing {
			rep.DriftItems = append(rep.DriftItems, fmt.Sprintf("missing artifact: %s", m.Path))
		}
		for _, dm := range status.DigestMismatch {
			rep.DriftItems = append(rep.DriftItems, fmt.Sprintf("artifact digest mismatch: %s (got %s, want %s)",
				dm.Artifact.Path, dm.Got[:12], dm.Want[:12]))
		}
	}
	if status.Unacknowledged() {
		rep.DriftItems = append(rep.DriftItems, fmt.Sprintf("unacknowledged version drift: live %s > ack ceiling %s",
			status.LiveVersion, status.AckedThrough))
	}

	rep.HasDrift = len(rep.DriftItems) > 0
	if rep.HasDrift {
		rep.Summary = fmt.Sprintf("DRIFT DETECTED: %d item(s) drifted against baseline", len(rep.DriftItems))
	} else {
		rep.Summary = "CLEAN: reference binary and evidence artifacts align with baseline"
	}

	return rep, nil
}

// FormatCanaryReport formats r as human-readable diagnostic text.
func FormatCanaryReport(r *CanaryReport) string {
	var b strings.Builder
	p := func(f string, a ...any) { b.WriteString(fmt.Sprintf(f, a...)) }

	p("=== AGY Canary & Reference Drift Report ===\n")
	p("Timestamp:        %s\n", r.Timestamp)
	p("Binary Path:      %s\n", r.BinaryPath)
	p("Binary Available: %v\n", r.Binary.Available)
	if r.Binary.Available {
		p("Binary Version:   %s (pinned: %s)\n", r.Version, r.PinnedVersion)
		p("Binary SHA-256:   %s\n", r.SHA256)
		p("Binary Size:      %d bytes\n", r.Binary.SizeBytes)
	}

	p("\n--- Subsystem Checks ---\n")
	// Methods
	statusM := "[OK]"
	if r.Methods.Drifted {
		statusM = "[DRIFT]"
	}
	p("Methods (%s):     %s - %d live RPCs (expected: %d)\n", r.Methods.ServiceName, statusM, r.Methods.LiveCount, r.Methods.ExpectedCount)
	for _, d := range r.Methods.Diff {
		p("                   * %s\n", d)
	}

	// Embed Assets
	statusE := "[OK]"
	if r.EmbedAssets.Drifted {
		statusE = "[DRIFT]"
	}
	p("Embed Assets:     %s - %d records, %d bytes, %d zip(s) (expected: %d)\n", statusE, r.EmbedAssets.LiveRecords, r.EmbedAssets.TotalBytes, r.EmbedAssets.ZipArchives, r.EmbedAssets.ExpectedRecords)
	for _, d := range r.EmbedAssets.Diff {
		p("                   * %s\n", d)
	}

	// Tools
	statusT := "[OK]"
	if r.Tools.Drifted {
		statusT = "[DRIFT]"
	}
	p("Tools Definition: %s - %d matched tools (expected: %d)\n", statusT, r.Tools.LiveCount, r.Tools.ExpectedCount)
	for _, d := range r.Tools.Diff {
		p("                   * %s\n", d)
	}

	p("\n--- Lock Artifacts Status ---\n")
	p("Pinned Version:   %s\n", r.Status.Pinned)
	p("Acked Through:    %s\n", r.Status.AckedThrough)
	p("Suspect Evidence: %d\n", len(r.Status.Suspect))
	p("Missing Evidence: %d\n", len(r.Status.Missing))
	p("Edited Evidence:  %d\n", len(r.Status.DigestMismatch))

	p("\n--- Summary ---\n")
	if r.HasDrift {
		p("[FAILED] %s\n", r.Summary)
		for i, item := range r.DriftItems {
			p("  %d. %s\n", i+1, item)
		}
	} else {
		p("[PASSED] %s\n", r.Summary)
	}
	return b.String()
}
