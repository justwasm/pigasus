package keybind

import (
	"os"
	"runtime"

	tea "charm.land/bubbletea/v2"
)

// MacOptionAsAltEnabled reports whether the macOS Option key should act
// as Alt/Meta out of the box.
//
// Reference 1.5.2 behavior:
// "Changed the default for macOS Option-key shortcuts such as alt+m, which now
// work out of the box without setting Option to act as Alt in your terminal,
// where previously pressing them did nothing or typed a character such as µ;
// set AGY_CLI_MAC_OPTION_AS_ALT=0 to go back to the old behavior."
func MacOptionAsAltEnabled() bool {
	if runtime.GOOS != "darwin" {
		return false
	}
	val := os.Getenv("AGY_CLI_MAC_OPTION_AS_ALT")
	return val != "0" && val != "false"
}

// macOptionRuneMap maps standard macOS Option+key Unicode characters back to the
// ASCII rune the user pressed with Option held.
//
// These cover the standard US/ABC keyboard layout characters generated by Option+<letter>.
var macOptionRuneMap = map[rune]rune{
	'å': 'a',
	'∫': 'b',
	'ç': 'c',
	'∂': 'd',
	'´': 'e',
	'ƒ': 'f',
	'©': 'g',
	'˙': 'h',
	'ˆ': 'i',
	'∆': 'j',
	'˚': 'k',
	'¬': 'l',
	'µ': 'm',
	'˜': 'n',
	'ø': 'o',
	'π': 'p',
	'œ': 'q',
	'®': 'r',
	'ß': 's',
	'†': 't',
	'¨': 'u',
	'√': 'v',
	'∑': 'w',
	'≈': 'x',
	'¥': 'y',
	'Ω': 'z',
}

// TranslateMacOptionToAlt converts a macOS Option-key generated rune into a tea.Key
// with ModAlt set if MacOptionAsAltEnabled is true.
// Returns the translated key and true if translated; returns original key and false otherwise.
func TranslateMacOptionToAlt(key tea.Key) (tea.Key, bool) {
	if !MacOptionAsAltEnabled() {
		return key, false
	}
	// If it already has Alt or Ctrl, do not double-translate.
	if key.Mod.Contains(tea.ModAlt) || key.Mod.Contains(tea.ModCtrl) {
		return key, false
	}
	if len(key.Text) == 0 {
		return key, false
	}
	r := []rune(key.Text)[0]
	if mapped, ok := macOptionRuneMap[r]; ok {
		return tea.Key{
			Code: mapped,
			Mod:  tea.ModAlt,
			Text: string(mapped),
		}, true
	}
	return key, false
}
