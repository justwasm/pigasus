func intPointer(n int) *int { return &n }

func TestModularityRatchetPassesAndReportsDeterministically(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, root, "internal/tui/a.go", `package tui
 type RootModel struct{}
 func (RootModel) View() string { return "" }
 func (*RootModel) Update() {}
`)
	writeTestFile(t, root, "internal/cli/b.go", "package cli\nfunc Run() {}\n")

	rep, err := analyze(options{root: root, ratchet: "enabled"})
	if err != nil {
		t.Fatal(err)
	}
	baseline := &modularityBaseline{Version: 1, Packages: map[string]packageCeiling{
		"internal/tui": {MaxLOC: intPointer(4), Receivers: map[string]*int{"RootModel": intPointer(2)}},
		"internal/cli": {MaxLOC: intPointer(2)},
	}}
	var stdout, stderr bytes.Buffer
	if code := printAndCheckRatchet(&stdout, &stderr, rep, baseline); code != 0 {
		t.Fatalf("ratchet exit=%d, stderr=%s", code, stderr.String())
	}
	want := "==> Modularity ratchet (direct-package production physical LOC/files; all build tags/platforms):\n" +
		"    internal/cli: LOC=2 ceiling=2 delta=+0 files=1\n" +
		"    internal/tui: LOC=4 ceiling=4 delta=+0 files=1\n" +
		"    internal/tui.RootModel: methods=2 ceiling=2 delta=+0\n" +
		"==> Modularity ratchet passed.\n"
	if stdout.String() != want {
		t.Fatalf("nondeterministic/unexpected output:\n%s\nwant:\n%s", stdout.String(), want)
	}
}

