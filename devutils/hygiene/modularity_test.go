func TestBaselineTypesEncodeAsExpected(t *testing.T) {
	baseline := modularityBaseline{Version: 1, SourceRevision: "aedbed1c", Packages: map[string]packageCeiling{
		"pkg": {MaxLOC: intPointer(5), Receivers: map[string]*int{"S": intPointer(1)}},
	}}
	encoded, err := json.Marshal(baseline)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(encoded), `"max_loc":5`) || !strings.Contains(string(encoded), `"receivers":{"S":1}`) {
		t.Fatalf("unexpected baseline JSON: %s", encoded)
	}
}
