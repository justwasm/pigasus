func TestModularityExcludesTestsAndGeneratedFiles(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, root, "pkg/source.go", "package pkg\nfunc (S) One() {}\n")
	writeTestFile(t, root, "pkg/source_test.go", "package pkg\nfunc (S) TestMethod() {}\n")
	writeTestFile(t, root, "pkg/types.pb.go", "package pkg\nfunc (S) PBMethod() {}\n")
	writeTestFile(t, root, "pkg/generated.go", "// Code generated by fixture. DO NOT EDIT.\npackage pkg\nfunc (S) GeneratedMethod() {}\n")
	rep, err := analyze(options{root: root, ratchet: "enabled", includeTests: true})
	if err != nil {
		t.Fatal(err)
	}
	got := rep.Packages["pkg"]
	if got == nil || got.Files != 1 || got.LOC != 2 || got.Receivers["S"] != 1 {
		t.Fatalf("excluded files affected metrics: %+v", got)
	}
}

func TestLoadModularityBaselineRejectsMissingMalformedAndInvalidConfig(t *testing.T) {
	root := t.TempDir()
	missing := filepath.Join(root, "missing.json")
	if _, err := loadModularityBaseline(missing); err == nil || !strings.Contains(err.Error(), "read ratchet baseline") {
		t.Fatalf("missing config error = %v", err)
	}
	cases := map[string]string{
		"malformed":        `{"version":`,
		"unknown field":    `{"version":1,"packages":{"pkg":{"max_loc":1,"mystery":2}}}`,
		"missing ceiling":  `{"version":1,"packages":{"pkg":{}}}`,
		"negative ceiling": `{"version":1,"packages":{"pkg":{"max_loc":-1}}}`,
		"invalid receiver": `{"version":1,"packages":{"pkg":{"max_loc":1,"receivers":{"S":null}}}}`,
		"trailing JSON":    `{"version":1,"packages":{"pkg":{"max_loc":1}}}{}`,
	}
	for name, content := range cases {
		t.Run(name, func(t *testing.T) {
			file := filepath.Join(root, name+".json")
			if err := os.WriteFile(file, []byte(content), 0o600); err != nil {
				t.Fatal(err)
			}
			if _, err := loadModularityBaseline(file); err == nil {
				t.Fatalf("accepted invalid baseline %q", content)
			}
		})
	}
}

func TestRunRatchetRequiresReadableReviewedConfig(t *testing.T) {
	root := t.TempDir()
	var stdout, stderr bytes.Buffer
	if code := run([]string{"-root", root, "-ratchet="}, &stdout, &stderr); code != 1 || !strings.Contains(stderr.String(), "requires a baseline JSON path") {
		t.Fatalf("empty ratchet: code=%d stderr=%s", code, stderr.String())
	}
	stdout.Reset()
	stderr.Reset()
	if code := run([]string{"-root", root, "-ratchet", filepath.Join(root, "missing.json")}, &stdout, &stderr); code != 1 || !strings.Contains(stderr.String(), "read ratchet baseline") {
		t.Fatalf("missing ratchet baseline: code=%d stderr=%s", code, stderr.String())
	}
}

