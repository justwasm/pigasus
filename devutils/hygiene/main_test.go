package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeTestFile(t *testing.T, root, rel, content string) {
	t.Helper()
	full := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		t.Fatalf("mkdir %s: %v", full, err)
	}
	if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
		t.Fatalf("write %s: %v", full, err)
	}
}

func TestAnalyzeComplexityAndTodos(t *testing.T) {
	root := t.TempDir()

	// Production file with one simple function, one complex method, and TODO/FIXME comments.
	writeTestFile(t, root, "pkg/sample.go", `package pkg

// TODO: refactor sample
type Svc struct{}

func simple() int {
	// String literal below must not be counted as a comment marker.
	_ = "TODO FIXME"
	return 1
}

// FIXME: simplify branching
func (s *Svc) complexMethod(a, b bool, xs []int) int {
	if a && b || !a {
		for i := 0; i < 3; i++ {
			switch i {
			case 0:
				return 1
			case 1:
				return 2
			default:
				return 3
			}
		}
	}
	for range xs {
		select {
		case <-make(chan struct{}):
		default:
		}
	}
	return 0
}
`)

	// Test file should be excluded by default from complexity and always from prod TODO/FIXME counts.
	writeTestFile(t, root, "pkg/sample_test.go", `package pkg

// TODO: test todo should not count in production summary
func TestComplex(a, b, c, d, e, f bool) {
	if a && b && c && d && e && f {
		return
	}
}
`)

	// Excluded directories and generated files.
	writeTestFile(t, root, "out/ignored.go", `package out
// TODO: ignored
func ignored(a, b, c, d, e, f bool) { if a && b && c && d && e && f {} }
`)
	writeTestFile(t, root, "scratch/ignored.go", `package scratch
// FIXME: ignored
func ignored(a, b, c, d, e, f bool) { if a && b && c && d && e && f {} }
`)
	writeTestFile(t, root, "node_modules/ignored.go", `package nm
// TODO: ignored
func ignored(a, b, c, d, e, f bool) { if a && b && c && d && e && f {} }
`)
	writeTestFile(t, root, "pkg/types.pb.go", `package pkg
// TODO: generated pb
func pb(a, b, c, d, e, f bool) { if a && b && c && d && e && f {} }
`)
	writeTestFile(t, root, "pkg/gen.go", `// Code generated by tool. DO NOT EDIT.
package pkg
// TODO: generated header
func gen(a, b, c, d, e, f bool) { if a && b && c && d && e && f {} }
`)

	// complexMethod complexity:
	// base(1) + if(1) + &&(1) + ||(1) + for(1) + case0(1) + case1(1) + range(1) + select-case(1) = 9.
	rep, err := analyze(options{
		root:          root,
		maxComplexity: 5,
		includeTests:  false,
	})
	if err != nil {
		t.Fatalf("analyze failed: %v", err)
	}

	if rep.ProdFilesScanned != 1 {
		t.Fatalf("ProdFilesScanned = %d, want 1", rep.ProdFilesScanned)
	}
	if rep.ComplexityFilesScanned != 1 {
		t.Fatalf("ComplexityFilesScanned = %d, want 1", rep.ComplexityFilesScanned)
	}
	if rep.TodoCount != 1 || rep.FixmeCount != 1 {
		t.Fatalf("TodoCount=%d FixmeCount=%d, want 1 and 1", rep.TodoCount, rep.FixmeCount)
	}
	if len(rep.ComplexFuncs) != 1 {
		t.Fatalf("len(ComplexFuncs) = %d, want 1 (%+v)", len(rep.ComplexFuncs), rep.ComplexFuncs)
	}
	got := rep.ComplexFuncs[0]
	if got.Name != "(*Svc).complexMethod" {
		t.Errorf("Name = %q, want (*Svc).complexMethod", got.Name)
	}
	if got.Complexity != 9 {
		t.Errorf("Complexity = %d, want 9", got.Complexity)
	}
	if got.File != "pkg/sample.go" {
		t.Errorf("File = %q, want pkg/sample.go", got.File)
	}

	// With includeTests=true, TestComplex (complexity 1 + 1 + 5 = 7) should also appear.
	repWithTests, err := analyze(options{
		root:          root,
		maxComplexity: 5,
		includeTests:  true,
	})
	if err != nil {
		t.Fatalf("analyze with tests failed: %v", err)
	}
	if repWithTests.ComplexityFilesScanned != 2 {
		t.Fatalf("ComplexityFilesScanned = %d, want 2", repWithTests.ComplexityFilesScanned)
	}
	if len(repWithTests.ComplexFuncs) != 2 {
		t.Fatalf("len(ComplexFuncs) = %d, want 2", len(repWithTests.ComplexFuncs))
	}
	if repWithTests.TodoCount != 1 || repWithTests.FixmeCount != 1 {
		t.Fatalf("production TODO/FIXME counts changed with includeTests: %d/%d", repWithTests.TodoCount, repWithTests.FixmeCount)
	}
}

func TestRunNonBlockingOutput(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, root, "a.go", `package a
// TODO: one
func f(a, b, c bool) {
	if a && b && c {
		return
	}
}
`)

	var stdout, stderr bytes.Buffer
	code := run([]string{"-root", root, "-max-complexity", "2"}, &stdout, &stderr)
	if code != 0 {
		t.Fatalf("run exit code = %d, want 0 (stderr=%s)", code, stderr.String())
	}
	out := stdout.String()
	if !strings.Contains(out, "WARNING: functions with cyclomatic complexity > 2") {
		t.Errorf("expected complexity warning in output, got:\n%s", out)
	}
	if !strings.Contains(out, "TODO=1, FIXME=0") {
		t.Errorf("expected TODO/FIXME summary in output, got:\n%s", out)
	}
}
