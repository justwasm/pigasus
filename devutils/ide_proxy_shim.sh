#!/usr/bin/env bash
# devutils/ide_proxy_shim.sh — helper to install/uninstall a local proxy shim
# for the official Antigravity.app language_server without modifying the binary.
#
# Usage:
#   ./devutils/ide_proxy_shim.sh status
#   ./devutils/ide_proxy_shim.sh install [proxy_port]
#   ./devutils/ide_proxy_shim.sh uninstall
set -euo pipefail

APP_BIN="/Applications/Antigravity.app/Contents/Resources/bin/language_server"
ORIG_BIN="${APP_BIN}.orig"
DEFAULT_PORT="8080"

status() {
    echo "=== Antigravity.app language_server shim status ==="
    if [ ! -e "${APP_BIN}" ] && [ ! -e "${ORIG_BIN}" ]; then
        echo "Error: ${APP_BIN} not found. Is Antigravity.app installed?" >&2
        return 1
    fi

    if [ -f "${ORIG_BIN}" ]; then
        echo "Status: SHIM INSTALLED"
        echo "  Wrapper: ${APP_BIN} ($(head -n 1 "${APP_BIN}"))"
        echo "  Original Mach-O: ${ORIG_BIN} ($(wc -c < "${ORIG_BIN}" | tr -d ' ') bytes)"
    else
        echo "Status: ORIGINAL BINARY (No shim installed)"
        echo "  Path: ${APP_BIN} ($(wc -c < "${APP_BIN}" | tr -d ' ') bytes)"
    fi
}

install_shim() {
    local port="${1:-$DEFAULT_PORT}"
    if [ ! -e "${APP_BIN}" ]; then
        echo "Error: ${APP_BIN} not found." >&2
        return 1
    fi

    if [ -f "${ORIG_BIN}" ]; then
        echo "Warning: ${ORIG_BIN} already exists. Updating existing wrapper port to ${port}..."
    else
        echo "Backing up original binary to ${ORIG_BIN}..."
        mv "${APP_BIN}" "${ORIG_BIN}"
    fi

    echo "Writing wrapper script to ${APP_BIN} (targeting 127.0.0.1:${port})..."
    cat << EOF > "${APP_BIN}"
#!/usr/bin/env bash
# Generated by openagy devutils/ide_proxy_shim.sh
DIR="\$(cd "\$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
REAL_SERVER="\${DIR}/language_server.orig"
PROXY_PORT="\${OPENAGY_PROXY_PORT:-${port}}"

export CLOUD_CODE_URL="http://127.0.0.1:\${PROXY_PORT}"

NEW_ARGS=()
for arg in "\$@"; do
    case "\$arg" in
        --cloud_code_endpoint=*)
            NEW_ARGS+=("--cloud_code_endpoint=http://127.0.0.1:\${PROXY_PORT}")
            ;;
        https://daily-cloudcode-pa.googleapis.com)
            NEW_ARGS+=("http://127.0.0.1:\${PROXY_PORT}")
            ;;
        *)
            NEW_ARGS+=("\$arg")
            ;;
    esac
done

exec "\${REAL_SERVER}" "\${NEW_ARGS[@]}"
EOF
    chmod +x "${APP_BIN}"
    echo "Shim installed successfully. Antigravity.app will now route CloudCode inference to http://127.0.0.1:${port}."
}

uninstall_shim() {
    if [ ! -f "${ORIG_BIN}" ]; then
        echo "No shim installed (${ORIG_BIN} does not exist)."
        return 0
    fi

    echo "Restoring original binary from ${ORIG_BIN}..."
    rm -f "${APP_BIN}"
    mv "${ORIG_BIN}" "${APP_BIN}"
    echo "Restored original binary successfully."
}

case "${1:-status}" in
    status)
        status
        ;;
    install)
        install_shim "${2:-$DEFAULT_PORT}"
        ;;
    uninstall)
        uninstall_shim
        ;;
    *)
        echo "Usage: $0 {status|install [port]|uninstall}" >&2
        exit 1
        ;;
esac
